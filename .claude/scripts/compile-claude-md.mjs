#!/usr/bin/env node
// L1 → L2 编译器：扫 docs/，按 frontmatter 生成 CLAUDE.md 的 AUTOGEN 索引段。
// 范围：docs/**/*.md，排除 docs/specs/**
// 失败模式：缺 frontmatter description / 缺 AUTOGEN 标记 → 退出码 1。

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DOCS_DIR = join(ROOT, 'docs');
const CLAUDE_MD = join(ROOT, 'CLAUDE.md');
const BEGIN = '<!-- BEGIN AUTOGEN — generated by .claude/scripts/compile-claude-md.mjs, do not edit -->';
const END = '<!-- END AUTOGEN -->';

function walk(dir, excludeRel = new Set()) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    const rel = relative(DOCS_DIR, path);
    if (excludeRel.has(rel) || [...excludeRel].some((ex) => rel.startsWith(ex + '/'))) continue;
    const st = statSync(path);
    if (st.isDirectory()) out.push(...walk(path, excludeRel));
    else if (name.endsWith('.md')) out.push(path);
  }
  return out;
}

function parseFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  if (!m) return null;
  const fields = {};
  for (const line of m[1].split('\n')) {
    const mm = line.match(/^([\w-]+):\s*(.*)$/);
    if (!mm) continue;
    let v = mm[2].trim();
    if (v.length >= 2 && ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'")))) {
      v = v.slice(1, -1);
    }
    fields[mm[1]] = v;
  }
  return fields;
}

function escapeRegex(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function compile() {
  const files = walk(DOCS_DIR, new Set(['specs'])).sort();
  const entries = [];
  const errors = [];

  for (const file of files) {
    const text = readFileSync(file, 'utf8');
    const fm = parseFrontmatter(text);
    const rel = relative(ROOT, file);
    if (!fm) {
      errors.push(`${rel}: 缺少 YAML frontmatter`);
      continue;
    }
    if (!fm.description) {
      errors.push(`${rel}: frontmatter 缺少 description 字段`);
      continue;
    }
    entries.push({ path: rel, description: fm.description, domain: fm.domain || 'misc' });
  }

  if (errors.length) {
    console.error('编译失败：');
    for (const e of errors) console.error('  - ' + e);
    process.exit(1);
  }

  // 扁平列表，每个文件一行，按路径字典序
  entries.sort((a, b) => a.path.localeCompare(b.path));
  const block = entries.map((e) => `- \`${e.path}\` — ${e.description}`).join('\n');

  let claude;
  try {
    claude = readFileSync(CLAUDE_MD, 'utf8');
  } catch {
    console.error(`找不到 ${relative(ROOT, CLAUDE_MD)} —— 先创建文件并加入 AUTOGEN 标记`);
    process.exit(1);
  }

  const re = new RegExp(`${escapeRegex(BEGIN)}[\\s\\S]*?${escapeRegex(END)}`);
  if (!re.test(claude)) {
    console.error(`CLAUDE.md 缺少 AUTOGEN 标记。请在希望生成索引的位置加入：\n${BEGIN}\n${END}`);
    process.exit(1);
  }

  const replacement = `${BEGIN}\n\n${block}\n\n${END}`;
  const updated = claude.replace(re, replacement);

  if (updated === claude) {
    console.log(`CLAUDE.md 无变更（${entries.length} 个 doc）`);
  } else {
    writeFileSync(CLAUDE_MD, updated);
    console.log(`CLAUDE.md 已更新（${entries.length} 个 doc）`);
  }
}

compile();
